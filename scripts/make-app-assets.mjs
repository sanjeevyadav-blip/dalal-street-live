// Generates the native app icon and splash sources — EPIC-6 story E6-2.
//
//   node scripts/make-app-assets.mjs && npx @capacitor/assets generate --android
//
// The acceptance is "matches design tokens", so nothing here invents a colour. Both images
// are rendered from the SAME mark the PWA manifest already carries — a gold Fraunces-ish D
// on --ink — so the installed app, the home-screen PWA and the website cannot drift apart.
// Shipping the default Capacitor logo would have been the obvious failure.
//
// The outputs are build inputs, not artefacts: assets/ is gitignored and regenerated on
// demand, the same way dist/ is.

import { mkdir, writeFile } from 'node:fs/promises';
import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import sharp from 'sharp';

const ROOT = process.cwd();
const OUT = resolve(ROOT, 'assets');

// Design tokens, copied here rather than imported: styles.css is CSS and this is a build
// script. They are asserted against each other in tests/unit/app-assets.test.js so the two
// copies cannot silently diverge.
const INK = '#0B1520';
const GOLD = '#C9A24B';

/** The mark, at any size. Identical geometry to the SVG in src/public/manifest.json. */
const markSvg = (size, { rounded = true } = {}) => `
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="${size}" height="${size}">
  <rect width="512" height="512" ${rounded ? 'rx="96"' : ''} fill="${INK}"/>
  <text x="256" y="330" font-family="Georgia,serif" font-size="280" font-weight="700"
        fill="${GOLD}" text-anchor="middle">D</text>
</svg>`;

/**
 * The splash is the mark centred on a flat ink field, deliberately small.
 *
 * Android crops the splash to the device aspect ratio from the centre, so anything near the
 * edges is lost on some handsets. Keeping the mark inside the middle third is what makes one
 * image work from a tall phone to a squat tablet.
 */
const splashSvg = (size) => {
  const mark = Math.round(size * 0.22);
  const offset = Math.round((size - mark) / 2);
  return `
<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}">
  <rect width="${size}" height="${size}" fill="${INK}"/>
  <g transform="translate(${offset}, ${offset})">
    <svg viewBox="0 0 512 512" width="${mark}" height="${mark}">
      <rect width="512" height="512" rx="96" fill="${INK}"/>
      <text x="256" y="330" font-family="Georgia,serif" font-size="280" font-weight="700"
            fill="${GOLD}" text-anchor="middle">D</text>
    </svg>
  </g>
</svg>`;
};

async function png(svg, size, file){
  await sharp(Buffer.from(svg)).resize(size, size).png().toFile(resolve(OUT, file));
  return file;
}

await mkdir(OUT, { recursive: true });

// @capacitor/assets expects these exact names and sizes.
const written = [];
written.push(await png(markSvg(1024), 1024, 'icon.png'));
// The foreground of an Android adaptive icon is masked to a circle on many launchers, and
// the outer 25% of the canvas is safe-zone padding. A square mark drawn edge to edge would
// have its corners shaved off, so the foreground is the letter on transparency, inset.
written.push(await png(`
<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024">
  <text x="512" y="660" font-family="Georgia,serif" font-size="480" font-weight="700"
        fill="${GOLD}" text-anchor="middle">D</text>
</svg>`, 1024, 'icon-foreground.png'));
written.push(await png(`
<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024">
  <rect width="1024" height="1024" fill="${INK}"/>
</svg>`, 1024, 'icon-background.png'));
written.push(await png(splashSvg(2732), 2732, 'splash.png'));
written.push(await png(splashSvg(2732), 2732, 'splash-dark.png'));

// Sanity-check that the mark actually rendered rather than producing a flat rectangle: a
// blank icon is easy to ship and hard to notice until it is on a home screen.
const icon = await sharp(resolve(OUT, 'icon.png')).stats();
const varied = icon.channels.some((c) => c.max - c.min > 40);
if (!varied){
  console.error('icon.png looks flat — the glyph did not render. Is a serif font available?');
  process.exit(1);
}

// Keep the PWA manifest and the native icon honest about being the same mark.
const manifest = JSON.parse(await readFile(resolve(ROOT, 'src/public/manifest.json'), 'utf8'));
if (manifest.background_color !== INK || manifest.theme_color !== INK){
  console.error('manifest colours have drifted from the tokens in this script');
  process.exit(1);
}

await writeFile(resolve(OUT, 'README.txt'),
  'Generated by scripts/make-app-assets.mjs from the design tokens. Do not edit by hand;\n' +
  'regenerate instead. Consumed by `npx @capacitor/assets generate --android`.\n');

console.log('wrote ' + written.length + ' source images to assets/:');
for (const f of written) console.log('  ' + f);
console.log('\nnext: npx @capacitor/assets generate --android');
